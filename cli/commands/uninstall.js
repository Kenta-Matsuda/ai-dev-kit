'use strict';
/**
 * `aidev uninstall` — remove ai-dev-kit from this machine.
 *
 * The installer (`scripts/install.ps1` / `install.sh`) leaves three things
 * behind, and this command takes back the two it can:
 *
 *   1. the launcher(s) in the bin directory (`aidev.cmd` / `aidev.ps1` on
 *      Windows, `aidev` on POSIX), plus the user-PATH entry install.ps1 added
 *   2. `AIDEV_HOME` (`registry.json`, `cache/`)
 *   3. the kit checkout the launcher points at (`installRoot`)
 *
 * The checkout is NOT deleted. It is the directory this very process runs
 * from — deleting it from inside is unreliable on Windows (cwd lock, AV
 * scanners) — and it may be a maintainer's working clone with uncommitted
 * changes. The user cloned it by hand; the command prints the one line that
 * removes it by hand.
 *
 * Packages are NOT touched either. What the kit placed in a PKG clone is
 * committed and shared by the whole team; deleting it is a team decision that
 * goes through a PR. `aidev eject` is the supported way while the CLI still
 * exists; for afterwards, this command prints the `git rm` that does the same
 * (and more: it also drops the Wiki and aidev.yaml, which eject keeps).
 *
 * Only launchers carrying the installer's "Generated by ai-dev-kit" marker are
 * removed. A file with the same name that somebody else put there is kept.
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');
const { EXIT, AidevError } = require('../lib/errors');
const assets = require('../lib/assets');
const home = require('../lib/home');
const pathsMod = require('../lib/paths');
const ui = require('../lib/ui');

const FLAGS = { yes: 'boolean', 'dry-run': 'boolean', json: 'boolean' };
const FLAG_HELP = {
  yes: 'remove the launcher and AIDEV_HOME; you have read the list',
  'dry-run': 'show what would be removed and the commands for the rest; write nothing',
  json: 'machine-readable output',
};

/** Written by both installers into every launcher they create. */
const LAUNCHER_MARKER = 'Generated by ai-dev-kit';
const LAUNCHER_NAMES = Object.freeze(['aidev.cmd', 'aidev.ps1', 'aidev']);

/** Where the installer put the launcher: the same rule as install.ps1 / install.sh. */
function defaultBinDir(env = process.env) {
  if (env.AIDEV_BIN_DIR) return path.resolve(env.AIDEV_BIN_DIR);
  if (process.platform === 'win32') {
    const base = env.LOCALAPPDATA || path.join(os.homedir(), 'AppData', 'Local');
    return path.join(base, 'ai-dev-kit', 'bin');
  }
  return path.join(os.homedir(), '.local', 'bin');
}

/** Launchers in binDir that this kit's installer generated. */
function listLaunchers(binDir) {
  const found = [];
  for (const name of LAUNCHER_NAMES) {
    const full = path.join(binDir, name);
    let text;
    try { if (!fs.statSync(full).isFile()) continue; text = fs.readFileSync(full, 'utf8'); } catch { continue; }
    if (text.includes(LAUNCHER_MARKER)) found.push(full);
  }
  return found;
}

/** Entries under AIDEV_HOME the CLI owns. Never the directory wholesale. */
function listHomeEntries(env = process.env) {
  const root = home.home(env);
  const out = [];
  for (const rel of ['registry.json', 'cache']) {
    const full = path.join(root, rel);
    if (fs.existsSync(full)) out.push(full);
  }
  return out;
}

function walk(dir, base, out) {
  let entries;
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) walk(full, base, out);
    else out.push(pathsMod.normalizeRel(path.relative(base, full)));
  }
}

/**
 * Fold kit-owned files into the highest directory that holds nothing else, so
 * the printed `git rm` reads `.claude/agents` rather than five agent files —
 * but stays file-level wherever the team keeps its own files next to ours
 * (`.claude/settings.local.json`, a team agent in `.github/agents/`).
 */
function collapsePaths(repoRoot, files) {
  const owned = new Set(files);
  const memo = new Map();
  const wholeDirOwned = (dirRel) => {
    if (memo.has(dirRel)) return memo.get(dirRel);
    const present = [];
    walk(path.join(repoRoot, ...dirRel.split('/')), repoRoot, present);
    const r = present.length > 0 && present.every((f) => owned.has(f));
    memo.set(dirRel, r);
    return r;
  };
  const out = new Set();
  for (const f of files) {
    let best = f;
    for (let dir = path.posix.dirname(f); dir && dir !== '.'; dir = path.posix.dirname(dir)) {
      if (!wholeDirOwned(dir)) break;
      best = dir;
    }
    out.add(best);
  }
  return [...out].sort();
}

/**
 * The commands that remove the kit from one registered PKG. Computed, never
 * run: the files are committed and shared, so removing them is a team change.
 */
function packageRemoval(pkgRoot, installRoot) {
  const files = assets.listStaticFiles(pkgRoot, { tools: assets.configuredTools(pkgRoot), installRoot });
  const paths = collapsePaths(pkgRoot, files);
  for (const rel of ['.aidev', 'aidev.yaml']) {
    if (fs.existsSync(path.join(pkgRoot, rel))) paths.push(rel);
  }
  const commands = [];
  if (paths.length > 0) commands.push(`git rm -r -q -- ${paths.join(' ')}`);
  if (paths.includes('.aidev')) {
    // git rm leaves the ignored runtime files (cache/, leases/ …) on disk.
    commands.push(process.platform === 'win32' ? 'Remove-Item -Recurse -Force .aidev' : 'rm -rf .aidev');
  }
  if (commands.length > 0) commands.push('git commit -m "chore: remove ai-dev-kit"');
  return { path: pkgRoot, paths, commands };
}

/**
 * Drop binDir from the user PATH that install.ps1 extended. Windows only, best
 * effort, and a write happens only when the entry is actually there. Returns
 * 'removed' | 'unchanged' | 'skipped' | 'failed'.
 */
function removeFromUserPath(binDir, { dryRun }) {
  if (process.platform !== 'win32') return 'skipped';
  const script = [
    "$p = [Environment]::GetEnvironmentVariable('Path', 'User'); if ($null -eq $p) { $p = '' }",
    "$needle = $env:AIDEV_UNINSTALL_BIN_DIR.TrimEnd('\\', '/')",
    "$parts = @($p -split ';' | Where-Object { $_ -ne '' })",
    "$kept = @($parts | Where-Object { $_.TrimEnd('\\', '/') -ine $needle })",
    'if ($kept.Count -eq $parts.Count) { \'unchanged\' }',
    dryRun
      ? "else { 'removed' }"
      : "else { [Environment]::SetEnvironmentVariable('Path', ($kept -join ';'), 'User'); 'removed' }",
  ].join('; ');
  try {
    const out = execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', script], {
      encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], timeout: 15000,
      env: { ...process.env, AIDEV_UNINSTALL_BIN_DIR: binDir },
    }).trim();
    return out === 'removed' || out === 'unchanged' ? out : 'failed';
  } catch { return 'failed'; }
}

function rmrf(p) {
  try { fs.rmSync(p, { recursive: true, force: true }); return true; } catch { return false; }
}

function pruneIfEmpty(dir) {
  try { if (fs.readdirSync(dir).length === 0) { fs.rmdirSync(dir); return true; } } catch { /* absent or busy */ }
  return false;
}

function checkoutRemovalCommand(installRoot) {
  return process.platform === 'win32'
    ? `Remove-Item -Recurse -Force "${installRoot}"`
    : `rm -rf "${installRoot}"`;
}

/** Everything uninstall would do, computed without writing anything. */
function planUninstall({ installRoot, env = process.env }) {
  const binDir = defaultBinDir(env);
  const launchers = listLaunchers(binDir);
  const homeDir = home.home(env);
  const homeEntries = listHomeEntries(env);
  const reg = home.listPackages(env);
  const packages = reg.present.map((p) => packageRemoval(p.path, installRoot));
  const missing = reg.missing.map((p) => p.path);
  return { binDir, launchers, homeDir, homeEntries, packages, missing, checkout: checkoutRemovalCommand(installRoot) };
}

function run(ctx) {
  const { flags, installRoot } = ctx;
  const dryRun = !!flags['dry-run'];
  const plan = planUninstall({ installRoot });
  const nothing = plan.launchers.length + plan.homeEntries.length === 0;

  if (!flags.json) {
    ui.heading(`aidev uninstall${dryRun ? ' (dry run)' : ''}`);
    ui.info('will remove from this machine:');
    for (const f of plan.launchers) ui.dim(`    ${f}`);
    for (const f of plan.homeEntries) ui.dim(`    ${f}`);
    if (nothing) ui.dim('    (nothing left to remove)');
    if (process.platform === 'win32') ui.dim(`    ${plan.binDir} from the user PATH (if present)`);
    ui.out('');
    ui.info('will keep (remove by hand when you are done):');
    ui.dim(`    the kit checkout   ${plan.checkout}`);
    if (plan.packages.length > 0) {
      ui.dim('    the files the kit placed in these packages (committed; removing them is a team change):');
      for (const p of plan.packages) {
        ui.dim(`      ${p.path}`);
        ui.dim('        before uninstalling (keeps the Wiki and aidev.yaml):   aidev eject --yes');
        ui.dim('        or by hand, in that clone (removes the Wiki too):');
        for (const c of p.commands) ui.dim(`          ${c}`);
      }
    }
    if (plan.missing.length > 0) {
      ui.dim(`    ${plan.missing.length} registered package(s) no longer on disk: ${plan.missing.join(', ')}`);
    }
  }

  if (dryRun) {
    const pathEntry = removeFromUserPath(plan.binDir, { dryRun: true });
    if (flags.json) {
      ui.json({
        ok: true, dryRun: true, launchers: plan.launchers, home: plan.homeEntries,
        pathEntry, checkout: plan.checkout, packages: plan.packages, missing: plan.missing,
      });
    } else {
      ui.out('');
      ui.ok('dry run: nothing was written.');
    }
    return EXIT.OK;
  }

  // Not a prompt: the same rule as eject, so a pipeline never hangs and the
  // confirmation is one explicit flag.
  if (!flags.yes) {
    throw new AidevError(
      'refusing to uninstall without confirmation. Re-run with --yes once you have read the list above,\n' +
      '    or use --dry-run to preview.');
  }

  const removed = [];
  for (const f of plan.launchers) if (rmrf(f)) removed.push(f);
  const pathEntry = removeFromUserPath(plan.binDir, { dryRun: false });
  for (const f of plan.homeEntries) if (rmrf(f)) removed.push(f);
  pruneIfEmpty(plan.binDir);
  pruneIfEmpty(plan.homeDir);

  if (flags.json) {
    ui.json({
      ok: true, removed, pathEntry, checkout: plan.checkout,
      packages: plan.packages, missing: plan.missing,
    });
    return EXIT.OK;
  }

  ui.out('');
  ui.ok(`removed ${removed.length} file(s)`);
  if (pathEntry === 'removed') ui.ok(`removed ${plan.binDir} from the user PATH (open a new terminal)`);
  else if (pathEntry === 'failed') ui.warn(`could not edit the user PATH; remove ${plan.binDir} from it by hand`);
  ui.out('');
  ui.info('the "aidev" command is gone from this machine.');
  ui.dim(`    kit checkout, delete by hand:   ${plan.checkout}`);
  ui.dim('    to install again: run scripts/install.ps1 or scripts/install.sh from a kit clone');
  return EXIT.OK;
}

module.exports = {
  run, FLAGS, FLAG_HELP, planUninstall, listLaunchers, collapsePaths, packageRemoval,
  defaultBinDir, LAUNCHER_MARKER,
  summary: 'この端末から aidev を消す（PKG と kit の clone は残し、消すコマンドを示す）',
};
