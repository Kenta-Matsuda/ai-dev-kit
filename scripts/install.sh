#!/usr/bin/env bash
# ai-dev-kit CLI bootstrap (macOS / Linux / WSL).
#
# Puts `aidev` on the user's PATH without requiring root. Node is the only
# runtime dependency; the CLI itself has no npm dependencies, so there is
# nothing to install beyond a launcher that points at this checkout.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN_DIR="${AIDEV_BIN_DIR:-$HOME/.local/bin}"
LAUNCHER="$BIN_DIR/aidev"
MIN_NODE_MAJOR=20

say()  { printf '  %s\n' "$*"; }
ok()   { printf '  \033[32m✓\033[0m %s\n' "$*"; }
warn() { printf '  \033[33m⚠\033[0m %s\n' "$*"; }
die()  { printf '  \033[31m✗\033[0m %s\n' "$*" >&2; exit 1; }

printf '\nai-dev-kit CLI install\n\n'

# --- runtime check -----------------------------------------------------------
command -v node >/dev/null 2>&1 || die "node not found. Install Node.js ${MIN_NODE_MAJOR}+ and re-run."

NODE_VERSION="$(node --version)"          # v22.17.1
NODE_MAJOR="${NODE_VERSION#v}"
NODE_MAJOR="${NODE_MAJOR%%.*}"
if [ "$NODE_MAJOR" -lt "$MIN_NODE_MAJOR" ]; then
  die "node ${NODE_VERSION} is too old; ${MIN_NODE_MAJOR}+ is required."
fi
ok "node ${NODE_VERSION}"

command -v git >/dev/null 2>&1 || die "git not found. Install git and re-run."
ok "$(git --version)"

[ -f "$REPO_ROOT/cli/bin/aidev.js" ] || die "cli/bin/aidev.js not found under ${REPO_ROOT}."

# --- launcher ----------------------------------------------------------------
# A launcher rather than a copy: `git pull` on the kit updates the CLI with no
# reinstall, and `aidev --version` always reports what is actually checked out.
mkdir -p "$BIN_DIR"

if [ -e "$LAUNCHER" ] && [ ! -f "$LAUNCHER" ]; then
  die "${LAUNCHER} exists and is not a regular file; remove it and re-run."
fi

cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Generated by ai-dev-kit scripts/install.sh — points at the kit checkout.
exec node "${REPO_ROOT}/cli/bin/aidev.js" "\$@"
EOF
chmod +x "$LAUNCHER"
ok "installed launcher: ${LAUNCHER}"

# --- PATH --------------------------------------------------------------------
case ":${PATH}:" in
  *":${BIN_DIR}:"*) ok "${BIN_DIR} is already on PATH" ;;
  *)
    warn "${BIN_DIR} is not on your PATH. Add this to your shell profile:"
    say  ""
    say  "    export PATH=\"${BIN_DIR}:\$PATH\""
    say  ""
    ;;
esac

# --- verify ------------------------------------------------------------------
INSTALLED_VERSION="$(node "${REPO_ROOT}/cli/bin/aidev.js" --version 2>/dev/null || true)"
[ -n "$INSTALLED_VERSION" ] || die "the CLI did not run. Try: node ${REPO_ROOT}/cli/bin/aidev.js --version"
ok "aidev ${INSTALLED_VERSION}"

printf '\n  next: aidev doctor\n\n'
