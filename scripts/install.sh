#!/usr/bin/env bash
# ai-dev-kit CLI bootstrap (macOS / Linux / WSL).
#
# Puts `aidev` on the user's PATH without requiring root. Node is the only
# runtime dependency; the CLI itself has no npm dependencies, so the launcher
# points at a dedicated ai-dev-kit checkout that `aidev update` fast-forwards.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
BIN_DIR="${AIDEV_BIN_DIR:-$HOME/.local/bin}"
LAUNCHER="$BIN_DIR/aidev"
MIN_NODE_MAJOR=20

say()  { printf '  %s\n' "$*"; }
ok()   { printf '  \033[32m✓\033[0m %s\n' "$*"; }
warn() { printf '  \033[33m⚠\033[0m %s\n' "$*"; }
die()  { printf '  \033[31m✗\033[0m %s\n' "$*" >&2; exit 1; }

printf '\nai-dev-kit CLI install\n\n'

# --- runtime check -----------------------------------------------------------
command -v node >/dev/null 2>&1 || die "node not found. Install Node.js ${MIN_NODE_MAJOR}+ and re-run."

NODE_VERSION="$(node --version)"          # v22.17.1
NODE_MAJOR="${NODE_VERSION#v}"
NODE_MAJOR="${NODE_MAJOR%%.*}"
if [ "$NODE_MAJOR" -lt "$MIN_NODE_MAJOR" ]; then
  die "node ${NODE_VERSION} is too old; ${MIN_NODE_MAJOR}+ is required."
fi
ok "node ${NODE_VERSION}"

command -v git >/dev/null 2>&1 || die "git not found. Install git and re-run."
ok "$(git --version)"

# The launcher must never be tied to a developer's PKG wrapper. `aidev update`
# advances the entire checkout that supplies the CLI. Azure Pipelines gets a
# compatibility exception for old wrapper pipelines; its launcher is ephemeral
# and the pipeline never invokes self-update.
REPO_TOP_LEVEL="$(git -C "$REPO_ROOT" rev-parse --show-toplevel 2>/dev/null)" || \
  die "${REPO_ROOT} is not a git checkout. Clone ai-dev-kit and run this installer from that clone."
REPO_TOP_LEVEL="$(cd "$REPO_TOP_LEVEL" && pwd -P)"
[ "$REPO_TOP_LEVEL" = "$REPO_ROOT" ] || \
  die "the CLI directory must be the root of its Git checkout: ${REPO_ROOT}"
git -C "$REPO_ROOT" remote get-url origin >/dev/null 2>&1 || \
  die "the dedicated ai-dev-kit checkout must have its central repository configured as origin."
CURRENT_BRANCH="$(git -C "$REPO_ROOT" rev-parse --abbrev-ref HEAD 2>/dev/null)" || \
  die "could not resolve the ai-dev-kit checkout branch."

IS_WRAPPER=false
if [ -f "$REPO_ROOT/aidev.yaml" ] || [ -f "$REPO_ROOT/.aidev-lock" ] || \
   [ -f "$REPO_ROOT/.aidev-ejected" ] || \
   git -C "$REPO_ROOT" remote get-url upstream >/dev/null 2>&1; then
  IS_WRAPPER=true
fi
if [ "$IS_WRAPPER" = true ] && [ "${TF_BUILD:-}" != "True" ]; then
  die "this checkout looks like a wrapper. Clone ai-dev-kit into a separate stable directory and run its installer."
fi
if [ "$IS_WRAPPER" = true ]; then
  warn "Azure Pipelines compatibility mode: installing an ephemeral wrapper CLI; self-update remains disabled."
elif [ "$CURRENT_BRANCH" != "main" ]; then
  die "the dedicated ai-dev-kit checkout must be on branch main (currently ${CURRENT_BRANCH})."
fi

[ -f "$REPO_ROOT/cli/bin/aidev.js" ] || die "cli/bin/aidev.js not found under ${REPO_ROOT}."

# --- launcher ----------------------------------------------------------------
# A launcher rather than a copy: `aidev update` fast-forwards the dedicated
# checkout, and `aidev --version` always reports what is actually checked out.
mkdir -p "$BIN_DIR"

if [ -e "$LAUNCHER" ] && [ ! -f "$LAUNCHER" ]; then
  die "${LAUNCHER} exists and is not a regular file; remove it and re-run."
fi

cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Generated by ai-dev-kit scripts/install.sh — points at the dedicated CLI checkout.
exec node "${REPO_ROOT}/cli/bin/aidev.js" "\$@"
EOF
chmod +x "$LAUNCHER"
ok "installed launcher: ${LAUNCHER}"

# --- PATH --------------------------------------------------------------------
case ":${PATH}:" in
  *":${BIN_DIR}:"*) ok "${BIN_DIR} is already on PATH" ;;
  *)
    warn "${BIN_DIR} is not on your PATH. Add this to your shell profile:"
    say  ""
    say  "    export PATH=\"${BIN_DIR}:\$PATH\""
    say  ""
    ;;
esac

# --- verify ------------------------------------------------------------------
INSTALLED_VERSION="$(node "${REPO_ROOT}/cli/bin/aidev.js" --version 2>/dev/null || true)"
[ -n "$INSTALLED_VERSION" ] || die "the CLI did not run. Try: node ${REPO_ROOT}/cli/bin/aidev.js --version"
ok "aidev ${INSTALLED_VERSION}"

printf '\n  next: aidev doctor\n\n'
