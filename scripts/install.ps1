<#
.SYNOPSIS
  ai-dev-kit CLI bootstrap (Windows / PowerShell).

.DESCRIPTION
  Puts `aidev` on the user's PATH without requiring administrator rights.
  Node is the only runtime dependency; the CLI has no npm dependencies, so
  this installs a launcher that points at this checkout rather than copying
  files. `git pull` on the kit then updates the CLI with no reinstall.

.PARAMETER BinDir
  Where to write the launcher. Defaults to %LOCALAPPDATA%\ai-dev-kit\bin.
#>
[CmdletBinding()]
param(
  [string] $BinDir = $(if ($env:AIDEV_BIN_DIR) { $env:AIDEV_BIN_DIR }
                       else { Join-Path $env:LOCALAPPDATA 'ai-dev-kit\bin' })
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$MinNodeMajor = 20
$RepoRoot = Split-Path -Parent $PSScriptRoot
$EntryPoint = Join-Path $RepoRoot 'cli\bin\aidev.js'

function Write-Ok   { param([string] $Message) Write-Host "  [ok] $Message" -ForegroundColor Green }
function Write-Warn { param([string] $Message) Write-Host "  [!]  $Message" -ForegroundColor Yellow }
function Stop-Install {
  param([string] $Message)
  Write-Host "  [x]  $Message" -ForegroundColor Red
  exit 1
}

# Semicolon-delimited PATH membership, compared case-insensitively and ignoring
# a trailing separator. Wrapped in @() because under Set-StrictMode a pipeline
# that filters everything out yields $null, and $null has no .Count -- reading
# it throws PropertyNotFoundException and, with $ErrorActionPreference = 'Stop',
# aborts the install before the PATH is ever updated.
function Test-PathContains {
  param(
    [AllowNull()] [string] $PathValue,
    [Parameter(Mandatory)] [string] $Directory
  )
  if ([string]::IsNullOrEmpty($PathValue)) { return $false }
  $needle = $Directory.TrimEnd('\', '/')
  $hits = @($PathValue -split ';' | Where-Object { $_ -and $_.TrimEnd('\', '/') -ieq $needle })
  return $hits.Count -gt 0
}

Write-Host "`nai-dev-kit CLI install`n"

# --- runtime check -----------------------------------------------------------
$node = Get-Command node -ErrorAction SilentlyContinue
if (-not $node) { Stop-Install "node not found. Install Node.js $MinNodeMajor+ and re-run." }

$nodeVersion = (& node --version).Trim()          # v22.17.1
$nodeMajor = [int](($nodeVersion.TrimStart('v') -split '\.')[0])
if ($nodeMajor -lt $MinNodeMajor) {
  Stop-Install "node $nodeVersion is too old; $MinNodeMajor+ is required."
}
Write-Ok "node $nodeVersion"

$git = Get-Command git -ErrorAction SilentlyContinue
if (-not $git) { Stop-Install 'git not found. Install git and re-run.' }
Write-Ok ((& git --version).Trim())

if (-not (Test-Path -LiteralPath $EntryPoint)) {
  Stop-Install "cli\bin\aidev.js not found under $RepoRoot."
}

# --- launcher ----------------------------------------------------------------
if (-not (Test-Path -LiteralPath $BinDir)) {
  New-Item -ItemType Directory -Path $BinDir -Force | Out-Null
}

# A .cmd shim works from cmd.exe, PowerShell and any tool that spawns `aidev`
# through the Windows path resolver -- which is what the hooks in
# .claude/settings.json rely on.
$shimPath = Join-Path $BinDir 'aidev.cmd'
@"
@echo off
REM Generated by ai-dev-kit scripts\install.ps1 -- points at the kit checkout.
node "$EntryPoint" %*
"@ | Set-Content -LiteralPath $shimPath -Encoding ASCII
Write-Ok "installed launcher: $shimPath"

# A PowerShell-native shim so `aidev` also resolves in PowerShell sessions that
# prefer .ps1 over .cmd on PATHEXT.
$ps1Path = Join-Path $BinDir 'aidev.ps1'
@"
#!/usr/bin/env pwsh
# Generated by ai-dev-kit scripts\install.ps1 -- points at the kit checkout.
& node "$EntryPoint" @args
exit `$LASTEXITCODE
"@ | Set-Content -LiteralPath $ps1Path -Encoding UTF8
Write-Ok "installed launcher: $ps1Path"

# --- PATH (user scope: no administrator rights required) ---------------------
$userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
if ($null -eq $userPath) { $userPath = '' }
$onPath = Test-PathContains -PathValue $userPath -Directory $BinDir

if ($onPath) {
  Write-Ok "$BinDir is already on your user PATH"
} else {
  $newPath = if ([string]::IsNullOrWhiteSpace($userPath)) { $BinDir } else { "$userPath;$BinDir" }
  [Environment]::SetEnvironmentVariable('Path', $newPath, 'User')
  Write-Ok "added $BinDir to your user PATH"
  Write-Warn 'Open a new terminal for the PATH change to take effect.'
}

# Make `aidev` usable in this session too, without waiting for a new terminal.
if (-not (Test-PathContains -PathValue $env:Path -Directory $BinDir)) {
  $env:Path = "$env:Path;$BinDir"
}

# --- verify ------------------------------------------------------------------
# PowerShell 7.4+ defaults $PSNativeCommandUseErrorActionPreference to $true, so
# a non-zero exit from node would raise a terminating error here and bypass the
# diagnostic below. Catching it keeps the actionable message reachable.
$installedVersion = $null
try {
  $installedVersion = & node $EntryPoint --version 2>$null | Select-Object -First 1
} catch {
  $installedVersion = $null
}
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($installedVersion)) {
  Stop-Install "the CLI did not run. Try: node `"$EntryPoint`" --version"
}
Write-Ok "aidev $($installedVersion.Trim())"

Write-Host "`n  next: aidev doctor`n"
